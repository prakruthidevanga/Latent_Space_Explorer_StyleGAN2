"""Streamlit UI for exploring StyleGAN2 latent-space interpolation."""
from __future__ import annotations

from pathlib import Path
import math

import matplotlib.pyplot as plt
import streamlit as st

from diagnostics import calculate_diagnostics, plot_latent_dimensions
from image_generator import CIFAR10_CLASSES, generate_image
from latent_utils import create_latent_from_seed, interpolate_latents, interpolation_parameters
from model_loader import ModelLoadError, load_stylegan2

ROOT = Path(__file__).resolve().parent
DEFAULT_MODEL_PATH = ROOT / "models" / "cifar10.pkl"
DEFAULT_REPO_PATH = ROOT / "third_party" / "stylegan2-ada-pytorch"


@st.cache_resource(show_spinner=False)
def cached_load_model(network_path: str, repo_path: str, device_choice: str):
    """Cache the loaded generator so Streamlit reruns don't reload its weights."""
    return load_stylegan2(network_path, repo_path, device_choice)


def _generate_session(seed_a: int, seed_b: int, steps: int, bundle, class_index: int, progress=None) -> dict:
    """Generate endpoint and gallery images, using actual model inference."""
    z_a = create_latent_from_seed(seed_a, bundle.z_dim)
    z_b = create_latent_from_seed(seed_b, bundle.z_dim)

    if progress:
        progress("Generating starting imageâ€¦")
    image_a = generate_image(bundle, z_a, class_index=class_index)
    if progress:
        progress("Generating ending imageâ€¦")
    image_b = generate_image(bundle, z_b, class_index=class_index)

    sequence = []
    parameters = interpolation_parameters(steps)
    for index, t in enumerate(parameters):
        if math.isclose(float(t), 0.0):
            image_t = image_a
        elif math.isclose(float(t), 1.0):
            image_t = image_b
        else:
            if progress:
                progress(f"Generating interpolation image {index + 1} of {len(parameters)} (t={float(t):.2f})â€¦")
            z_t = interpolate_latents(z_a, z_b, float(t))
            image_t = generate_image(bundle, z_t, class_index=class_index)
        z_t = interpolate_latents(z_a, z_b, float(t))
        sequence.append({"t": float(t), "latent": z_t, "image": image_t})

    return {
        "seed_a": seed_a,
        "seed_b": seed_b,
        "network_path": str(DEFAULT_MODEL_PATH if not st.session_state.get("network_path") else st.session_state["network_path"]),
        "z_a": z_a,
        "z_b": z_b,
        "image_a": image_a,
        "image_b": image_b,
        "sequence": sequence,
        "z_dim": bundle.z_dim,
        "model_name": bundle.model_name,
        "device": str(bundle.device),
        "class_index": class_index,
        "class_label": CIFAR10_CLASSES[class_index] if bundle.c_dim == 10 else "unconditional",
        "img_resolution": bundle.img_resolution,
    }


def main() -> None:
    st.set_page_config(page_title="Latent Space Explorer", page_icon="ðŸ§¬", layout="wide")
    st.title("ðŸ§¬ Latent Space Explorer")
    st.write(
        "Explore how moving between two latent vectors changes images generated by a "
        "pretrained StyleGAN2-ADA model. The interpolation happens in latent spaceâ€”not by blending image pixels."
    )

    with st.sidebar:
        st.header("Controls")
        seed_a = int(st.number_input("Seed A", min_value=0, max_value=2**32 - 1, value=17, step=1))
        seed_b = int(st.number_input("Seed B", min_value=0, max_value=2**32 - 1, value=83, step=1))
        t = st.slider("Latent interpolation (t)", min_value=0.0, max_value=1.0, value=0.5, step=0.05)
        steps = st.selectbox("Images in interpolation sequence (including endpoints)", options=[3, 5, 7], index=0)
        class_label = st.selectbox("Image class (CIFAR-10)", options=CIFAR10_CLASSES, index=3, help="The official CIFAR-10 checkpoint is class-conditional. Default: cat.")
        class_index = CIFAR10_CLASSES.index(class_label)
        device_choice = st.selectbox("Inference device", options=["Auto", "CPU", "CUDA"], index=0)
        network_path = st.text_input("Pretrained checkpoint (.pkl)", value=str(DEFAULT_MODEL_PATH))
        repo_path = st.text_input("StyleGAN2-ADA PyTorch source folder", value=str(DEFAULT_REPO_PATH))
        st.caption("CPU-friendly official StyleGAN2-ADA checkpoint: CIFAR-10 (native 32 Ã— 32, displayed enlarged for easier viewing).")
        generate_clicked = st.button("Generate / refresh images", type="primary", width="stretch")

    st.markdown("### How the interpolation works")
    st.latex(r"z(t) = (1-t)z_A + tz_B, \quad 0 \leq t \leq 1")
    explanation_cols = st.columns(3)
    explanation_cols[0].info("**t = 0**\n\nReturns the starting latent vector and image.")
    explanation_cols[1].info("**t = 0.5**\n\nReturns the midpoint between the two vectors.")
    explanation_cols[2].info("**t = 1**\n\nReturns the ending latent vector and image.")

    current_key = (seed_a, seed_b, str(Path(network_path).expanduser()), str(Path(repo_path).expanduser()), device_choice, steps, class_index)
    if generate_clicked:
        try:
            with st.status("Loading the pretrained model and generating imagesâ€¦", expanded=True) as status:
                status.write("Loading model checkpointâ€¦")                
                checkpoint_path = Path(network_path).expanduser()

                if (
                    not checkpoint_path.is_file()
                    and checkpoint_path.resolve()
                    == DEFAULT_MODEL_PATH.resolve()
                ):
                    status.write(
                        "Downloading the CIFAR-10 model checkpoint..."
                    )

                    subprocess.run(
                        [
                            sys.executable,
                            str(ROOT / "download_model.py"),
                            "--model",
                            "cifar10",
                            "--output",
                            str(checkpoint_path),
                        ],
                        cwd=str(ROOT),
                        check=True,
                    )

                status.write("Loading model checkpoint...")
                bundle = cached_load_model(network_path, repo_path, device_choice)
                if bundle.c_dim not in (0, 10):
                    raise ModelLoadError(
                        f"This interface supports unconditional models or the 10-class CIFAR-10 model; checkpoint c_dim={bundle.c_dim}."
                    )
                status.write(f"Model loaded: {bundle.model_name}; device: {bundle.device}; native resolution: {bundle.img_resolution} Ã— {bundle.img_resolution}.")
                result = _generate_session(seed_a, seed_b, steps, bundle, class_index, progress=status.write)
                result["key"] = current_key
                result["network_path"] = network_path
                result["repo_path"] = repo_path
                result["device_choice"] = device_choice
                st.session_state["latent_result"] = result
                st.session_state.pop("current_image_cache", None)
                status.update(label="Image generation complete", state="complete", expanded=False)
            st.success("Images generated by the pretrained model.")
        except Exception as exc:  # Display errors so a failed model load doesn't crash the UI.
            st.error(f"Could not generate images: {exc}")
            with st.expander("Setup checklist", expanded=True):
                st.markdown(
                    "1. Clone the official StyleGAN2-ADA PyTorch repository into the source folder above.\n"
                    "2. Download `cifar10.pkl` using `python download_model.py --model cifar10`.\n"
                    "3. Check the installation steps in `README.md`.\n\n"
                    "A simulation or placeholder image is not presented as real model inference."
                )

    result = st.session_state.get("latent_result")
    if not result:
        st.warning("The interface is ready. Download the pretrained checkpoint and official model code, then click **Generate / refresh images**.")
        st.markdown("**Official model source:** [NVlabs/stylegan2-ada-pytorch](https://github.com/NVlabs/stylegan2-ada-pytorch)")
        st.code(
            "python download_model.py --model cifar10\n"
            "git clone https://github.com/NVlabs/stylegan2-ada-pytorch.git third_party/stylegan2-ada-pytorch\n"
            "streamlit run app.py",
            language="powershell",
        )
        st.stop()

    if result.get("key") != current_key:
        st.info("You changed a seed, model path, device, or step count. Click **Generate / refresh images** to apply those changes.")

    # Keep the last successful result visible while controls are being edited.
    bundle = None
    active_t = float(t)
    selected_entry = min(result["sequence"], key=lambda entry: abs(entry["t"] - active_t))
    if math.isclose(selected_entry["t"], active_t, abs_tol=1e-9):
        current_image = selected_entry["image"]
        current_latent = selected_entry["latent"]
    else:
        image_cache_key = (result.get("key"), active_t)
        image_cache = st.session_state.get("current_image_cache")
        if image_cache and image_cache.get("key") == image_cache_key:
            current_image = image_cache["image"]
            current_latent = image_cache["latent"]
        elif result.get("key") == current_key:
            try:
                with st.spinner(f"Generating image at t = {active_t:.2f}â€¦"):
                    bundle = cached_load_model(network_path, repo_path, device_choice)
                    current_latent = interpolate_latents(result["z_a"], result["z_b"], active_t)
                    current_image = generate_image(bundle, current_latent, class_index=class_index)
                    st.session_state["current_image_cache"] = {
                        "key": image_cache_key,
                        "image": current_image,
                        "latent": current_latent,
                    }
            except Exception as exc:
                st.error(f"Could not generate the current interpolated image: {exc}")
                current_image = selected_entry["image"]
                current_latent = selected_entry["latent"]
        else:
            current_image = selected_entry["image"]
            current_latent = selected_entry["latent"]

    st.markdown("### Generated images")
    st.caption(f"Class: {result.get('class_label', class_label)} Â· Native model resolution: {result.get('img_resolution', '?')} Ã— {result.get('img_resolution', '?')}. CIFAR-10 images are enlarged for display only.")
    c1, c2, c3 = st.columns(3)
    with c1:
        st.image(result["image_a"], caption=f"Start image Â· Seed {result['seed_a']} Â· t = 0.00", width="stretch")
    with c2:
        st.image(current_image, caption=f"Current interpolation Â· t = {active_t:.2f}", width="stretch")
    with c3:
        st.image(result["image_b"], caption=f"End image Â· Seed {result['seed_b']} Â· t = 1.00", width="stretch")

    st.markdown("### Interpolation gallery")
    st.caption("Each gallery image is generated from its own interpolated latent vector. Both endpoint images are included.")
    entries = result["sequence"]
    for start in range(0, len(entries), 5):
        row = st.columns(min(5, len(entries) - start))
        for col, entry in zip(row, entries[start:start + 5]):
            with col:
                st.image(entry["image"], caption=f"t = {entry['t']:.2f}", width="stretch")

    diag = calculate_diagnostics(result["z_a"], result["z_b"], current_latent)
    st.markdown("### Latent-space diagnostics")
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Latent dimensions", str(result["z_dim"]))
    m2.metric("Endpoint L2 distance", f"{diag['endpoint_distance']:.3f}")
    m3.metric("Distance from start", f"{diag['distance_from_start']:.3f}")
    m4.metric("Distance from end", f"{diag['distance_from_end']:.3f}")
    st.caption(
        f"Model: {result['model_name']} Â· Device: {result['device']} Â· "
        f"Images in gallery: {len(entries)} Â· Class: {result.get('class_label', class_label)}. L2 distance measures numerical distance between latent vectors, not perceptual image similarity."
    )
    fig = plot_latent_dimensions(result["z_a"], result["z_b"], current_latent)
    st.pyplot(fig, clear_figure=True)
    plt.close(fig)

    with st.expander("How this application works", expanded=False):
        st.markdown(
            "1. Each seed initializes a separate random-number generator and produces a reproducible Z-space vector.\n"
            "2. The interpolation function computes `z(t) = (1 - t) * z_A + t * z_B`.\n"
            "3. The actual pretrained StyleGAN2 generator maps each Z vector through its learned mapping network and synthesis network.\n"
            "4. The returned image tensor is converted to a displayable image.\n"
            "5. The diagnostics report latent-vector distances; they do not claim to measure human-perceived similarity."
        )


if __name__ == "__main__":
    main()

